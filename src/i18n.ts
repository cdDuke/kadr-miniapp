export type Key = keyof (typeof dict)['ru'];

export function useT() {
  const lang = useStore((s) => s.lang);
  const t = useCallback(
    (key: Key, vars: Record<string, string | number> = {}) => (dict[lang][key] as string).replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? '')),
    [lang]
  );
  const locale = lang === 'ru' ? 'ru-RU' : 'en-GB';
  const money = useCallback((n: number) => new Intl.NumberFormat(locale, { style: 'currency', currency: 'RUB', maximumFractionDigits: 0 }).format(n), [locale]);
  const genre = useCallback((g: Genre) => dict[lang][`g.${g}`], [lang]);
  return { t, lang, locale, money, genre };
}

export function duration(minutes: number, t: ReturnType<typeof useT>['t']) {
  return t('min', { h: Math.floor(minutes / 60), m: minutes % 60 });
}
